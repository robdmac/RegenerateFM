#!/usr/bin/env python3
"""Build regeneratefm-progress, the window FM26 shows while BepInEx prepares it.

    python3 native/fm26progress/build.py [--windows] [--macos] [--cc CC]

BepInEx's first start in a game folder, and its first after an FM26 update,
makes FM26's interop assemblies before the game appears, with nothing on
screen. regeneratefm-progress watches BepInEx/LogOutput.log and, only while
BepInEx is doing that, shows a small window with a progress bar in FM26's
language. Otherwise it exits without showing anything.

- Windows (and Proton): regeneratefm-progress.exe, plain Win32 (MinGW-w64,
  x86_64-w64-mingw32-gcc by default). RegenerateFM.Start.dll, which Doorstop
  loads before BepInEx, starts it.
- macOS: regeneratefm-progress, AppKit, for arm64 and x86_64 (Xcode's
  command-line tools). run_regeneratefm.sh starts it.

Both read their text from build/progress_strings.h or ProgressStrings.swift,
generated here from src/RegenerateFM.Core/Translations. With neither option
it builds what this system can.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TRANSLATIONS = ROOT / "src" / "RegenerateFM.Core" / "Translations"
# The window's text, in this order in both builds.
TEXTS = ["Preparing FM26 for RegenerateFM",
         "This happens once, the first time FM26 starts with RegenerateFM, and again after an FM26 update. "
         "Later starts are as quick as before.",
         "Downloading Unity's libraries…", "Reading FM26's code…", "Building RegenerateFM's link to FM26…",
         "Starting FM26…"]


def languages() -> list[tuple[str, list[str]]]:
    """(FM's language name, the texts) for each translation: "spanish (latam)" for spanish-latam.json."""
    found = []
    for path in sorted(TRANSLATIONS.glob("*.json")):
        table = json.loads(path.read_text(encoding="utf-8"))
        name = path.stem.replace("-", " (", 1) + ")" if "-" in path.stem else path.stem
        found.append((name, [table.get(text) or text for text in TEXTS]))
    return found


def c_wide(text: str) -> str:
    """A C wide-string literal, with everything outside printable ASCII escaped."""
    out = []
    for char in text:
        code = ord(char)
        if char in '"\\':
            out.append("\\" + char)
        elif 32 <= code < 127:
            out.append(char)
        elif code <= 0xFFFF:
            out.append(f"\\u{code:04x}")
        else:
            out.append(f"\\U{code:08x}")
    return 'L"' + "".join(out) + '"'


def write_c_strings(output: Path) -> None:
    lines = ["/* Generated by native/fm26progress/build.py from src/RegenerateFM.Core/Translations. */",
             f"#define TEXT_COUNT {len(TEXTS)}",
             "static const wchar_t *const ENGLISH[TEXT_COUNT] = {" + ", ".join(c_wide(t) for t in TEXTS) + "};",
             "static const struct { const char *language; const wchar_t *const texts[TEXT_COUNT]; } TRANSLATED[] = {"]
    for name, texts in languages():
        lines.append(f'    {{"{name}", {{' + ", ".join(c_wide(t) for t in texts) + "}},")
    lines.append("};")
    (output / "progress_strings.h").write_text("\n".join(lines) + "\n", encoding="ascii")


def write_swift_strings(output: Path) -> None:
    lines = ["// Generated by native/fm26progress/build.py from src/RegenerateFM.Core/Translations.",
             "let englishTexts = " + json.dumps(TEXTS, ensure_ascii=False),
             "let translatedTexts: [String: [String]] = ["]
    for name, texts in languages():
        lines.append(f"    {json.dumps(name)}: {json.dumps(texts, ensure_ascii=False)},")
    lines.append("]")
    (output / "ProgressStrings.swift").write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(*command: str | Path) -> None:
    print("+", " ".join(map(str, command)))
    subprocess.run([str(part) for part in command], check=True)


def build_windows(output: Path, cc: str) -> None:
    write_c_strings(output)
    run(cc, "-O2", "-Wall", "-municode", "-mwindows", "-static", "-I", output,
        "-o", output / "regeneratefm-progress.exe", HERE / "progress_windows.c",
        "-lcomctl32", "-lgdi32", "-lshell32")


def build_macos(output: Path) -> None:
    write_swift_strings(output)
    slices = []
    for arch in ("arm64", "x86_64"):
        target = output / f"regeneratefm-progress-{arch}"
        run("xcrun", "swiftc", "-O", "-target", f"{arch}-apple-macos12.0", "-o", target,
            HERE / "progress_macos.swift", output / "ProgressStrings.swift")
        slices.append(target)
    run("lipo", "-create", "-output", output / "regeneratefm-progress", *slices)
    for target in slices:
        target.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--windows", action="store_true")
    parser.add_argument("--macos", action="store_true")
    parser.add_argument("--cc", default="x86_64-w64-mingw32-gcc")
    parser.add_argument("--output", type=Path, default=HERE / "build")
    args = parser.parse_args()
    windows, macos = args.windows, args.macos
    if not windows and not macos:
        windows = shutil.which(args.cc) is not None
        macos = sys.platform == "darwin"
    if macos and sys.platform != "darwin":
        parser.error("The macOS build needs a Mac.")
    if windows and not shutil.which(args.cc):
        parser.error(f"{args.cc} (MinGW-w64) is needed for the Windows build; supply --cc if it has another name.")
    args.output.mkdir(parents=True, exist_ok=True)
    if windows:
        build_windows(args.output, args.cc)
    if macos:
        build_macos(args.output)


if __name__ == "__main__":
    main()
